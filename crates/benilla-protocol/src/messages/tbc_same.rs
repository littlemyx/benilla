/// The 1.12.1 opcode whose reader reads the 2.4.3 `opcode`, `None` when it is not on the table.
pub fn same_reader_for(opcode: u16) -> Option<u16> {
    TBC_SAME_READERS
        .binary_search_by_key(&opcode, |&(n, _)| n)
        .ok()
        .map(|i| TBC_SAME_READERS[i].1)
}
